import { mkdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
const root = resolve(".local");
const data = join(root, "postgres");
const bin = process.env.POSTGRES_BIN || "/opt/homebrew/opt/postgresql@15/bin";
const action = process.argv[2];
function run(name, args) {
  const r = spawnSync(join(bin, name), args, { stdio: "inherit" });
  if (r.error) throw r.error;
  if (r.status) process.exit(r.status);
}
mkdirSync(root, { recursive: true, mode: 0o700 });
if (action === "init") {
  if (existsSync(".env.local")) {
    if (!readFileSync(".env.local", "utf8").includes("127.0.0.1:55438/mimacro"))
      throw Error(
        "Existing .env.local is not the dedicated local configuration; refusing to overwrite.",
      );
  } else {
    const password = randomBytes(32).toString("hex");
    writeFileSync(join(root, "db-password"), password, { mode: 0o600 });
    writeFileSync(
      ".env.local",
      `DATABASE_URL=postgresql://mimacro:${password}@127.0.0.1:55438/mimacro\nAPP_ORIGIN=http://127.0.0.1:3006\nPRIVATE_STORAGE_DIR=.local/storage\nAI_ENABLED=false\n`,
      { mode: 0o600 },
    );
  }
  if (!existsSync(join(data, "PG_VERSION"))) {
    if (!existsSync(join(root, "db-password")))
      throw Error("Missing local DB password file.");
    run("initdb", [
      "-D",
      data,
      "-U",
      "mimacro",
      "--encoding=UTF8",
      "--no-locale",
      "--auth-host=scram-sha-256",
      "--auth-local=trust",
      "--pwfile=" + join(root, "db-password"),
    ]);
  }
  console.log("Dedicated cluster initialized. Next: npm run db:start");
} else if (action === "start") {
  if (!existsSync(join(data, "PG_VERSION")))
    throw Error("Run npm run db:init first.");
  const active =
    spawnSync(join(bin, "pg_ctl"), ["-D", data, "status"], { stdio: "ignore" })
      .status === 0;
  if (!active)
    run("pg_ctl", [
      "-D",
      data,
      "-l",
      join(root, "postgres.log"),
      "-o",
      "-h 127.0.0.1 -p 55438 -c unix_socket_directories=''",
      "start",
      "-w",
    ]);
  // This connection string is generated by this script; never touches another instance.
  const password = readFileSync(join(root, "db-password"), "utf8").trim();
  if (!/^[a-f0-9]{64}$/.test(password))
    throw Error("Invalid dedicated local DB password file.");
  const args = ["-h", "127.0.0.1", "-p", "55438", "-U", "mimacro"];
  const childenv = {
    ...process.env,
    PGPASSWORD: password,
  };
  const has = spawnSync(
    join(bin, "psql"),
    [
      ...args,
      "-d",
      "postgres",
      "-tAc",
      "SELECT 1 FROM pg_database WHERE datname='mimacro'",
    ],
    { env: childenv, encoding: "utf8" },
  );
  if (has.status) throw Error("Cannot connect to dedicated local database.");
  if (has.stdout.trim() !== "1") {
    const r = spawnSync(join(bin, "createdb"), [...args, "mimacro"], {
      env: childenv,
      stdio: "inherit",
    });
    if (r.status) process.exit(r.status);
  }
  console.log("Local PostgreSQL ready on 127.0.0.1:55438 (database mimacro).");
} else if (action === "stop") {
  run("pg_ctl", ["-D", data, "stop", "-m", "fast"]);
} else throw Error("Use init, start or stop.");
